#!/usr/bin/env node
/**
 * Generate backend/src/main/resources/ddinter-pairs.sql from the DDInter 2.0
 * bulk CSVs.
 *
 * Usage:
 *   curl -s http://localhost:8080/api/interactions -o backend/tools/existing-pairs.json
 *   node backend/tools/import-ddinter.js /path/to/ddinter/downloads
 *
 * existing-pairs.json is only used to skip pairs the catalogue already has;
 * refresh it from a running API before regenerating.
 *
 * Source: DDInter 2.0 (https://ddinter2.scbdd.com), downloaded 2026-11-14.
 * Licence: CC BY-NC-SA 4.0. Non-commercial use only; derived data must keep
 * the same licence and attribution. Do not ship in a paid product.
 *
 * Only pairs where both drugs are already in our catalogue are emitted, every
 * DDInter level is kept (Unknown becomes UNKNOWN), and pairs already present in
 * data.sql are skipped so curated rows always win.
 */
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node import-ddinter.js <dir-with-ddinter-csvs>');
  process.exit(1);
}

// Catalogue names (must match drug.name exactly) and the DDInter spellings
// that map onto them.
const ALIASES = {
  Aspirin: ['Acetylsalicylic acid'],
  Furosemide: ['Frusemide'],
  'Co-trimoxazole': ['Cotrimoxazole', 'Sulfamethoxazole/trimethoprim', 'Trimethoprim/sulfamethoxazole'],
  Paracetamol: ['Acetaminophen'],
  'Insulin glargine': ['Insulin Glargine'],
  Metoprolol: ['Metoprolol tartrate', 'Metoprolol succinate'],
};

const RANK = { Major: 3, Moderate: 2, Minor: 1, Unknown: 0 };
const SEVERITY = { Major: 'HIGH', Moderate: 'MEDIUM', Minor: 'LOW', Unknown: 'UNKNOWN' };

const pairs = new Map();
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.csv'))) {
  const lines = fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/);
  for (const line of lines.slice(1)) {
    if (!line.trim()) continue;
    const m = line.match(/^(.*),(.*),(.*),(.*),(.*)$/);
    if (!m) continue;
    const a = m[2].trim();
    const b = m[4].trim();
    const level = m[5].trim();
    if (!(level in RANK)) continue; // Unexpected level: skip rather than guess
    const key = [a, b].sort().join(' | ');
    const prev = pairs.get(key);
    if (!prev || RANK[level] > RANK[prev.level]) pairs.set(key, { a, b, level });
  }
}

const byName = new Map();
for (const [canonical, list] of Object.entries(ALIASES)) {
  byName.set(canonical.toLowerCase(), canonical);
  for (const alias of list) byName.set(alias.toLowerCase(), canonical);
}

// Look up a DDInter name, falling back to the catalogue name itself.
function canonical(name) {
  return byName.get(name.toLowerCase()) || name;
}

const existing = JSON.parse(fs.readFileSync(path.join(__dirname, 'existing-pairs.json'), 'utf8'));
const existingKeys = new Set(
  existing.map((p) => [p.drug1, p.drug2].sort().join(' | '))
);

// Only pairs where both drugs are in our catalogue matter. DDInter's
// "Unknown" level is kept as UNKNOWN, never mapped onto MEDIUM.
const catalogue = new Set(Object.keys(ALIASES).concat(existing.flatMap((p) => [p.drug1, p.drug2])));
const rows = [];
const seen = new Set();
for (const { a, b, level } of pairs.values()) {
  const n1 = canonical(a);
  const n2 = canonical(b);
  if (n1 === n2) continue;
  if (!catalogue.has(n1) || !catalogue.has(n2)) continue;
  const key = [n1, n2].sort().join(' | ');
  if (existingKeys.has(key) || seen.has(key)) continue;
  seen.add(key);
  rows.push({ n1, n2, level });
}
rows.sort((x, y) => (x.n1 + x.n2).localeCompare(y.n1 + y.n2));

const esc = (s) => s.replace(/'/g, "''");
const values = rows
  .map((r) => `    SELECT '${esc(r.n1)}' AS n1, '${esc(r.n2)}' AS n2, '${SEVERITY[r.level]}' AS severity`)
  .join('\n    UNION ALL\n');

const sql = `-- DDInter 2.0 pairs for the 40 catalogue drugs.
-- Generated by backend/tools/import-ddinter.js. Do not edit by hand.
--
-- Source: DDInter 2.0 (https://ddinter2.scbdd.com), downloaded 2026-11-14.
-- Licence: CC BY-NC-SA 4.0 (attribution, non-commercial, share-alike).
-- Every DDInter level is included. Its "Unknown" level is kept as UNKNOWN
-- rather than guessed into a graded severity.
-- Existing pairs are never touched, so the curated rows in data.sql win.
--
-- ${rows.length} pairs.

-- Rows created before this import are the curated set.
UPDATE interaction SET source = 'CURATED' WHERE source IS NULL;

INSERT INTO interaction (drug1_id, drug2_id, severity, description, mechanism, management, evidence, source)
SELECT d1.id, d2.id, x.severity,
       CONCAT('Imported from DDInter 2.0 (', LOWER(x.severity), '). No summary recorded.'),
       'Mechanism not recorded for this imported pair.',
       'Review the DDInter 2.0 entry and local guidance before combining.',
       'DDInter 2.0',
       'DDINTER'
FROM (
${values}
) x
JOIN drug d1 ON d1.name = x.n1
JOIN drug d2 ON d2.name = x.n2
WHERE NOT EXISTS (
    SELECT 1 FROM interaction i
    WHERE (i.drug1_id = d1.id AND i.drug2_id = d2.id)
       OR (i.drug1_id = d2.id AND i.drug2_id = d1.id)
)
-- Guard against emitting the same pair twice if the catalogue ever gains an
-- alias that maps two DDInter names onto one row.
AND d1.id <> d2.id;

UPDATE interaction SET source = 'CURATED' WHERE source IS NULL;
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'main', 'resources', 'ddinter-pairs.sql'), sql);
console.log(`wrote ${rows.length} pairs`);
const byLevel = {};
for (const r of rows) byLevel[r.level] = (byLevel[r.level] || 0) + 1;
console.log('levels:', JSON.stringify(byLevel));
